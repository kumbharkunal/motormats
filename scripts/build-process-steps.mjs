// @ts-check
/**
 * The five "how it's made" illustrations, taken from the client's folder.
 *
 * **Drop files in `motormats/steps/` and rerun.** The filename is a number that
 * sets the order — `1.webp` is step 01 — and nothing else here needs editing.
 * `motormats/` is gitignored, so the copies written into `public/` are what
 * actually ship.
 *
 * **The files are copied, not re-encoded.** They arrive as webp at roughly
 * 0.35 bits per pixel, which is already a sensible encode; running them through
 * a lossy encoder a second time would only throw away detail that the line work
 * in these drawings cannot spare. They are also small enough (about 395px wide)
 * that there is no second width worth emitting — a card renders them at roughly
 * 260 CSS px, so the master is barely above 1x and resizing could only make it
 * worse. What this script is for is the dimensions: the manifest carries the
 * real width and height of each file so the cards reserve their space and the
 * section cannot shift as the art loads.
 *
 * Run: node scripts/build-process-steps.mjs
 */
import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import sharp from 'sharp';

const SOURCE = 'motormats/steps';
const OUT = 'public/process';

const NAME = /^(\d+)\.(webp|png|jpe?g)$/i;

const entries = await readdir(SOURCE);

const steps = entries
  .map((file) => {
    const match = NAME.exec(file);
    return match ? { order: Number(match[1]), file } : null;
  })
  .filter((step) => step !== null)
  .sort((a, b) => a.order - b.order);

if (steps.length === 0) {
  throw new Error(`No numbered illustrations found in ${SOURCE} — expected 1.webp, 2.webp, …`);
}

await mkdir(OUT, { recursive: true });

/** @type {string[]} */
const manifestEntries = [];

for (const [index, step] of steps.entries()) {
  const source = path.join(SOURCE, step.file);
  const info = await sharp(source).metadata();

  if (info.format !== 'webp') {
    throw new Error(
      `${source} is ${info.format}, not webp. Convert it first — this script copies rather than re-encodes.`,
    );
  }

  const name = `step-${index + 1}.webp`;
  await copyFile(source, path.join(OUT, name));

  manifestEntries.push(
    `  { src: '/process/${name}', width: ${info.width}, height: ${info.height} },`,
  );
  console.log(`step-${index + 1}`.padEnd(8), `${info.width}x${info.height}`, `<- ${step.file}`);
}

const manifest = `// Generated by scripts/build-process-steps.mjs — do not edit by hand.
//
// Geometry only. What each illustration depicts, and the copy beside it, are
// editorial and live in the section that renders them.

export type ProcessArt = {
  src: string;
  width: number;
  height: number;
};

export const PROCESS_ART: ProcessArt[] = [
${manifestEntries.join('\n')}
];
`;

await writeFile('src/features/home/process-art.ts', manifest, 'utf8');
console.log(`\n${steps.length} illustration(s) -> src/features/home/process-art.ts`);
