// @ts-check
/**
 * Grid-sized cuts of the photo library.
 *
 * `public/photos/*.webp` are full-plate files — 100KB to 760KB each, sized for a
 * frame that fills half a screen. A gallery shows two dozen of them at a few
 * hundred pixels wide, and `next/image` cannot help: `images.loader` is custom
 * with no resizer in front of `public/`, so every one of those files ships at
 * full size no matter what `sizes` says. Two dozen came to roughly seven
 * megabytes. These are the same frames at the widths a grid tile actually uses,
 * served through native `srcSet`, which needs no resizer at all.
 *
 * The source here is `public/photos` rather than the camera masters, which live
 * in `images-deck/_hd` and are not checked in. That means a second lossy pass —
 * acceptable only because every output is *smaller* than its input, and
 * downsampling discards the first pass's artefacts along with the detail. Never
 * re-encode one of these at or above its source width.
 *
 * Run: node scripts/build-photo-grid.mjs
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import sharp from 'sharp';

const SOURCE = 'public/photos';
const OUT = 'public/photos/grid';

/** A tile is at most half a phone, a third of a tablet, a quarter of a desktop. */
const WIDTHS = [400, 640, 900];

const entries = (await readdir(SOURCE, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith('.webp'))
  .map((entry) => entry.name)
  .sort();

if (entries.length === 0) throw new Error(`No photographs found in ${SOURCE}`);

await mkdir(OUT, { recursive: true });

/** @type {string[]} */
const manifestEntries = [];
let saved = 0;

for (const file of entries) {
  const name = path.basename(file, '.webp');
  const source = path.join(SOURCE, file);
  const info = await sharp(source).metadata();
  const sourceWidth = info.width ?? 0;
  const ratio = sourceWidth / (info.height || 1);

  /** @type {string[]} */
  const set = [];
  let widest = 0;

  for (const target of WIDTHS) {
    // Never emit at or above the source width — that is the upscale that makes
    // a second encode actually cost quality rather than just bytes.
    if (target >= sourceWidth) continue;
    const out = `${name}-${target}.webp`;
    await sharp(source).resize({ width: target }).webp({ quality: 80, effort: 6 }).toFile(path.join(OUT, out));
    set.push(`/photos/grid/${out} ${target}w`);
    widest = target;
  }

  if (set.length === 0) {
    console.warn(`skipped ${file} — already narrower than ${WIDTHS[0]}px`);
    continue;
  }

  manifestEntries.push(
    `  '${name}': { src: '/photos/grid/${name}-${widest}.webp', srcSet: '${set.join(', ')}', width: ${widest}, height: ${Math.round(widest / ratio)} },`,
  );
  saved += 1;
}

const manifest = `// Generated by scripts/build-photo-grid.mjs — do not edit by hand.
//
// Grid-sized cuts of /public/photos, keyed by the frame's own name. Consumed by
// PhotoPlate, which renders a plain <img srcSet> — the custom image loader has
// no resizer, so native srcSet is the only thing that serves a smaller file.
//
// Alt text is not here: it belongs with the frame in photo-assets.ts.

export type PhotoCut = {
  src: string;
  srcSet: string;
  width: number;
  height: number;
};

export const PHOTO_GRID: Record<string, PhotoCut | undefined> = {
${manifestEntries.join('\n')}
};

/** The grid cut for a \`/photos/<name>.webp\` source, if one was generated. */
export function photoCutFor(src: string): PhotoCut | undefined {
  const name = src.replace(/^.*\\//, '').replace(/\\.webp$/, '');
  return PHOTO_GRID[name];
}
`;

await writeFile('src/features/home/photo-grid.ts', manifest, 'utf8');
console.log(`${saved} frame(s) -> src/features/home/photo-grid.ts`);
